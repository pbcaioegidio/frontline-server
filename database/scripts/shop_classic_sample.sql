SELECT item_id, item_name, left(price_gold_list,40) g, left(price_cash_list,40) c
FROM system_shop
WHERE item_visible AND shop_tag = 0 AND (
  item_id IN (
    104001,104008,104011, -- MP5K, UMP45, P90 Ext
    105001,105002,105003,105004,105005,105006,105007,105008,105009,105010,
    106001,106002,106003,106004,106005,106006,106007,106008,106009,106010,
    202001,202002,202003,202004,202005,202006,202007,202008,202009,202010,202022,
    301001,301002,301003,301004,301005,301006,301007,301008,301009,301010,301012
  )
  OR (item_id BETWEEN 105001 AND 105030 AND length(item_name) < 20)
  OR (item_id BETWEEN 106001 AND 106030 AND length(item_name) < 22)
  OR (item_id BETWEEN 104001 AND 104020 AND length(item_name) < 18)
)
ORDER BY item_id;
