-- Writes the active preset into the table the server reads. Same guarded pair the panel's
-- rankRewardPresetActivate mutation runs, and they must stay separate statements: a DELETE in a
-- data-modifying CTE shares the INSERT's snapshot, so the reinserted (rank_id, ordinal) keys
-- collide with the rows the CTE just removed.
--
-- The DELETE requires an active preset that awards at least one good to a rank that exists. The
-- partial unique index only promises at most one active preset, and `rewards` stays editable, so
-- a weaker guard would empty every promotion reward and reinsert nothing.
DELETE FROM public.system_player_rank_rewards
WHERE EXISTS (
    SELECT 1
    FROM public.system_player_rank_reward_presets AS candidate,
         jsonb_each(candidate.rewards::jsonb) AS entry(rank_id, goods),
         jsonb_array_elements_text(entry.goods) AS good(value)
    WHERE candidate.active
      AND EXISTS (SELECT 1 FROM public.system_player_ranks r WHERE r.id = entry.rank_id::integer)
);

INSERT INTO public.system_player_rank_rewards (rank_id, ordinal, good_id)
SELECT entry.rank_id::integer, good.ordinal - 1, good.value::integer
FROM public.system_player_rank_reward_presets AS preset,
     jsonb_each(preset.rewards::jsonb) AS entry(rank_id, goods),
     jsonb_array_elements_text(entry.goods) WITH ORDINALITY AS good(value, ordinal)
WHERE preset.active
  AND EXISTS (SELECT 1 FROM public.system_player_ranks r WHERE r.id = entry.rank_id::integer);

