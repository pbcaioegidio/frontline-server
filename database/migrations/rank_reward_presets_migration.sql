-- system_player_rank_reward_presets: swappable rank-promotion reward sets for the web panel.
--
-- One row per preset. `rewards` is {"<rank_id>":[good_id,...]} in award order, and `active`
-- marks the set currently written into system_player_rank_rewards, which is the table
-- Plugin.Core/SQL/DaoManagerSQL.GetPlayerRanks actually reads into RankModel.Rewards.
-- Activating a preset rewrites system_player_rank_rewards, so an xml reload puts it live.
--
-- The partial unique index is the invariant: at most one preset may be active, enforced by the
-- database and not only by the panel.
--
-- Every good_id here exists in system_shop and is shop_valid in the client index, because
-- AllUtils.GrantRankRewards silently skips an id ShopManager cannot resolve.
-- Generated by tools/pb-dev/gen_rank_reward_presets.py.

CREATE TABLE IF NOT EXISTS public.system_player_rank_reward_presets (
    name character varying(64) NOT NULL,
    label character varying(120) DEFAULT '' NOT NULL,
    active boolean DEFAULT false NOT NULL,
    rewards character varying(8000) DEFAULT '{}' NOT NULL,
    CONSTRAINT system_player_rank_reward_presets_pkey PRIMARY KEY (name)
);

CREATE UNIQUE INDEX IF NOT EXISTS system_player_rank_reward_presets_one_active
    ON public.system_player_rank_reward_presets ((active)) WHERE active;

