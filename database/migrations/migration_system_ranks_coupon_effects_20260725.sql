CREATE TABLE IF NOT EXISTS system_player_ranks (
    id            integer PRIMARY KEY,
    title         text    NOT NULL DEFAULT '',
    on_next_level integer NOT NULL DEFAULT 0,
    on_gold_up    integer NOT NULL DEFAULT 0,
    on_all_exp    integer NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS system_player_rank_rewards (
    rank_id integer NOT NULL REFERENCES system_player_ranks(id) ON DELETE CASCADE,
    ordinal integer NOT NULL,
    good_id integer NOT NULL,
    PRIMARY KEY (rank_id, ordinal)
);

CREATE TABLE IF NOT EXISTS system_clan_ranks (
    id            integer PRIMARY KEY,
    title         text    NOT NULL DEFAULT '',
    on_next_level integer NOT NULL DEFAULT 0,
    on_all_exp    integer NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS system_coupon_effects (
    item_id     integer PRIMARY KEY,
    effect_flag text    NOT NULL
);

